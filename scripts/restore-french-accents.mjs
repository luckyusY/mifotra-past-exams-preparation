function accentWord(word) {
  const lower = word.toLowerCase();
  const rep = MAP[lower];
  if (!rep) return word;
  // preserve capitalisation of the first letter
  if (word[0] === word[0].toUpperCase() && word[0] !== word[0].toLowerCase()) {
    return rep[0].toUpperCase() + rep.slice(1);
  }
  return rep;
}

// Match whole words including already-accented ones, so re-running is a no-op
// rather than chopping "medecin" out of "médecin".
const WORD = /[A-Za-zÀ-ÿ]+/g;

/**
 * Every standalone "a" in this corpus is the preposition "à" - checked by
 * listing them all in context. The one exception is the English phrase
 * "Software as a Service", which appears untranslated in an option.
 */
function fixPrepositionA(s) {
  return s.replace(/(\w+)?(\s+)a(\s+)/g, (m, prev, sp1, sp2) =>
    prev?.toLowerCase() === 'as' ? m : `${prev ?? ''}${sp1}à${sp2}`
  );
}

const fix = (s) => fixPrepositionA(s.replace(WORD, accentWord));

const path = 'data/mifotra-2024.json';
const doc = JSON.parse(fs.readFileSync(path, 'utf8'));

let changed = 0;
for (const q of doc.questions) {
  const before = JSON.stringify(q.fr);
  q.fr.stem = fix(q.fr.stem);
  q.fr.options = q.fr.options.map(fix);
  q.fr.explanation = fix(q.fr.explanation);
  if (JSON.stringify(q.fr) !== before) changed++;
}

fs.writeFileSync(path, JSON.stringify(doc, null, 2) + '\n');
console.log(`accented French text in ${changed} of ${doc.questions.length} questions`);
